#include <stdarg.h>  // 可変長引数リストを扱うために必要
#include <stdio.h>

/*
================================================================================
 1. 基本的な関数定義 (ANSI C 形式)
================================================================================
現代のC言語で最も標準的な形式。
戻り値の型、関数名、そして引数の型と名前を明確に宣言します。
*/

// 引数も戻り値もない関数
void function_no_args_no_return() {
  printf("1. 引数も戻り値もない関数が呼ばれました。\n");
}

// 引数があり、戻り値がない関数
void function_with_args_no_return(int a, int b) {
  printf("2. 引数あり、戻り値なしの関数が呼ばれました。受け取った値: %d, %d\n",
         a, b);
}

// 引数も戻り値もある関数
int add(int a, int b) { return a + b; }

/*
================================================================================
 2. K&R (Kernighan & Ritchie) 形式の関数定義
================================================================================
ANSI
Cが標準化される前の古い形式。現在では非推奨ですが、古いコードで見かけることがあります。
引数の型は、関数名の後の行で宣言します。
*/
int old_style_add(a, b)
int a;
int b;
{
  return a + b;
}

/*
================================================================================
 3. static 修飾子を付けた関数
================================================================================
`static`を付けて定義された関数は、その関数が定義されたファイル内からのみ可視（呼び出し可能）となります。
これにより、他のファイルとの名前の衝突を防いだり、ファイル内部の処理をカプセル化したりできます。
*/
static void internal_function() {
  printf("5. このファイル内でのみ呼び出し可能なstatic関数です。\n");
}

/*
================================================================================
 4. inline 修飾子を付けた関数
================================================================================
コンパイラに対して、この関数の呼び出しをインライン展開（関数呼び出しのオーバーヘッドをなくすために、
関数の中身を呼び出し元に直接埋め込むこと）するようにヒントを与えます。
主に、非常に小さく、頻繁に呼び出される関数に対して使用されます。
*/
inline int multiply(int a, int b) { return a * b; }

/*
================================================================================
 5. ポインタを返す関数
================================================================================
関数がポインタを返すことも可能です。動的に確保したメモリ領域のアドレスや、
静的変数・グローバル変数のアドレスを返す際によく使われます。
*/
int global_variable = 100;

int* get_global_variable_address() { return &global_variable; }

/*
================================================================================
 6. 可変長引数を取る関数
================================================================================
`printf`のように、引数の数が可変である関数を定義することもできます。
`stdarg.h`ヘッダの機能を使って実装します。
*/
int sum_all(int count, ...) {
  int total = 0;
  va_list args;  // 引数リストを指すポインタ

  va_start(args, count);  // 可変長引数リストの初期化

  for (int i = 0; i < count; ++i) {
    total += va_arg(args, int);  // 次の引数をint型として取得
  }

  va_end(args);  // 後片付け

  return total;
}

/*
================================================================================
 main 関数 : ここからプログラムが実行されます
================================================================================
*/
int main() {
  printf("--- C言語 関数定義のサンプル集 ---\n\n");

  // 1. 引数も戻り値もない関数
  function_no_args_no_return();

  // 2. 引数があり、戻り値がない関数
  function_with_args_no_return(10, 20);

  // 3. 引数も戻り値もある関数 (ANSI C形式)
  int result_ansi = add(5, 3);
  printf("3. add(5, 3) の結果: %d\n", result_ansi);

  // 4. K&R形式の関数
  int result_kr = old_style_add(5, 3);
  printf("4. old_style_add(5, 3) の結果: %d\n", result_kr);

  // 5. static関数 (このファイル内なので呼び出せる)
  internal_function();

  // 6. inline関数
  int result_inline = multiply(7, 7);
  printf("6. multiply(7, 7) の結果: %d\n", result_inline);

  // 7. ポインタを返す関数
  int* p = get_global_variable_address();
  printf("7. ポインタを返す関数から受け取った値: %d\n", *p);
  *p = 200;  // ポインタ経由でグローバル変数を変更
  printf("   -> ポインタ経由で変更後のグローバル変数の値: %d\n",
         global_variable);

  // 8. 可変長引数を取る関数
  int total = sum_all(4, 10, 20, 30, 40);  // 4つの引数 (10, 20, 30, 40) を渡す
  printf("8. sum_all(4, 10, 20, 30, 40) の結果: %d\n", total);

  printf("\n--- 実行終了 ---\n");
  return 0;
}